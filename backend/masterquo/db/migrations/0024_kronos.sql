-- Kronos (NeoQuasar/Kronos-small) SHADOW forecasts: stored BEFORE the outcome, settled later from real closed bars (additive).
CREATE TABLE IF NOT EXISTS kronos_forecasts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    forecast_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    instrument TEXT NOT NULL,
    symbol TEXT NOT NULL,
    timeframe TEXT NOT NULL,
    horizon_bars INTEGER NOT NULL,
    last_bar_open_utc TEXT NOT NULL,
    last_close REAL NOT NULL,
    pred_close_h REAL NOT NULL,
    delta_price REAL NOT NULL,
    direction TEXT NOT NULL,
    neutral_band REAL,
    path_json TEXT NOT NULL,
    uncertainty_json TEXT,
    model_revision TEXT,
    tokenizer_revision TEXT,
    device TEXT,
    compute_ms REAL,
    data_kind TEXT NOT NULL,
    volume_source TEXT,
    quality_status TEXT,
    settings_json TEXT,
    outcome_status TEXT NOT NULL DEFAULT 'PENDING',
    actual_close_h REAL,
    abs_err_h REAL,
    naive_abs_err_h REAL,
    path_mae REAL,
    direction_actual TEXT,
    direction_hit INTEGER,
    outcome_json TEXT,
    settled_at TEXT,
    UNIQUE(instrument, timeframe, last_bar_open_utc, horizon_bars, settings_json)
);
CREATE INDEX IF NOT EXISTS ix_kronos_fc ON kronos_forecasts(instrument, timeframe, outcome_status);
