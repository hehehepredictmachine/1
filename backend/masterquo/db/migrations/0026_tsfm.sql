-- 1.37 Chronos-2 / FinCast forecasts (additive; Kronos keeps kronos_forecasts). Stored BEFORE the outcome, settled later only from
-- real closed bars of exactly the target times. One row = one model fingerprint + profile + snapshot + horizon.
CREATE TABLE IF NOT EXISTS tsfm_forecasts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    forecast_id TEXT NOT NULL UNIQUE,
    model_id TEXT NOT NULL,
    model_name TEXT NOT NULL,
    model_revision TEXT NOT NULL,
    fingerprint TEXT NOT NULL,
    profile TEXT NOT NULL,
    snapshot_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    instrument TEXT NOT NULL,
    symbol TEXT NOT NULL,
    data_source TEXT,
    timeframe TEXT NOT NULL,
    horizon_bars INTEGER NOT NULL,
    context_bars INTEGER NOT NULL,
    last_bar_open_utc TEXT NOT NULL,
    data_available_at TEXT,
    valid_until TEXT,
    last_close REAL NOT NULL,
    point_kind TEXT NOT NULL,
    pred_close_h REAL NOT NULL,
    median_close_h REAL,
    delta_price REAL NOT NULL,
    direction TEXT NOT NULL,
    neutral_band REAL,
    path_json TEXT NOT NULL,
    quantiles_json TEXT,
    input_hash TEXT,
    device TEXT,
    compute_ms REAL,
    data_kind TEXT NOT NULL,
    quality_status TEXT,
    settings_json TEXT,
    outcome_status TEXT NOT NULL DEFAULT 'PENDING',
    actual_close_h REAL,
    abs_err_h REAL,
    naive_abs_err_h REAL,
    path_mae REAL,
    pinball_h REAL,
    covered_80 INTEGER,
    direction_actual TEXT,
    direction_hit INTEGER,
    outcome_json TEXT,
    settled_at TEXT,
    UNIQUE(model_id, fingerprint, profile, instrument, timeframe, last_bar_open_utc, horizon_bars)
);
CREATE INDEX IF NOT EXISTS ix_tsfm_fc ON tsfm_forecasts(model_id, instrument, timeframe, outcome_status);
CREATE INDEX IF NOT EXISTS ix_tsfm_bar ON tsfm_forecasts(instrument, timeframe, last_bar_open_utc);
