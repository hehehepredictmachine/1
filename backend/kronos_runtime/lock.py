def component_dir_name(c: dict) -> str:
    """Folder of one component inside the weights directory: <owner>__<name>@<revision>."""
    return c["repo"].replace("/", "__") + "@" + c["revision"]


def name_of(repo: str | None, revision: str | None = None) -> str:
    """Display name of a model revision stored in history (Kronos-small rows stay Kronos-small)."""
    for c in (MODEL, *LEGACY):
        if repo == c["repo"] or (revision and revision == c["revision"]):
            return c["name"]
    return str(repo or "Kronos (nieznana rewizja)")


